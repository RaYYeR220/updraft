// Generates src/generated.ts from the Foundry build output, Ascend's token creation code and the
// deployment record, so the SDK always matches the contracts it ships with.
// Run after `forge build` in ../../contracts: `pnpm gen`.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const out = join(root, "contracts", "out");

const contracts: Record<string, string> = {
  updraftFactoryAbi: "UpdraftFactory.sol/UpdraftFactory.json",
  updraftRoundAbi: "UpdraftRound.sol/UpdraftRound.json",
  creatorVaultAbi: "CreatorVault.sol/CreatorVault.json",
  launchCertificateAbi: "LaunchCertificate.sol/LaunchCertificate.json",
  updraftStakingAbi: "UpdraftStaking.sol/UpdraftStaking.json",
  updraftLensAbi: "UpdraftLens.sol/UpdraftLens.json",
  ascendLaunchpadAbi: "IAscendLaunchpad.sol/IAscendLaunchpad.json",
};

let ts = "// Generated by scripts/gen.ts. Do not edit.\n\n";
for (const [name, file] of Object.entries(contracts)) {
  const artifact = JSON.parse(readFileSync(join(out, file), "utf8"));
  ts += `export const ${name} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}

const tokenCode = readFileSync(join(root, "contracts", "src", "ascend", "AscendTokenCode.sol"), "utf8");
const hex = /hex"([0-9a-fA-F]+)"/.exec(tokenCode)?.[1];
if (!hex) throw new Error("Ascend token creation code not found");
ts += `export const ascendTokenCreationCode = "0x${hex}" as const;\n\n`;

const deploymentPath = join(root, "deployments", "elysium-testnet.json");
if (existsSync(deploymentPath)) {
  const d = JSON.parse(readFileSync(deploymentPath, "utf8"));
  ts += `export const elysiumTestnetDeployment = ${JSON.stringify(d, null, 2)} as const;\n`;
} else {
  ts += "export const elysiumTestnetDeployment = undefined;\n";
}

writeFileSync(join(here, "..", "src", "generated.ts"), ts);
console.log("wrote src/generated.ts");
