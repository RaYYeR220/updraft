#!/usr/bin/env bash
# Regenerates src/ascend/AscendTokenCode.sol from any token launched through Ascend:
# the token's creation bytecode minus its ABI-encoded constructor arguments.
# Usage: script/fetch-token-code.sh <token address>
set -euo pipefail

TOKEN=$1
API=${BLOCKSCOUT_API:-https://elysium.kinetiq.xyz/api/v2}
RPC=${ELYSIUM_RPC:-https://testnet-rpc.elysium.kinetiq.xyz}
OUT=$(dirname "$0")/../src/ascend/AscendTokenCode.sol

creation=$(curl -fsS "$API/smart-contracts/$TOKEN" | python -c 'import json,sys; print(json.load(sys.stdin)["creation_bytecode"])')
name=$(cast call "$TOKEN" "name()(string)" --rpc-url "$RPC" | sed 's/^"//; s/"$//')
symbol=$(cast call "$TOKEN" "symbol()(string)" --rpc-url "$RPC" | sed 's/^"//; s/"$//')
args=$(cast abi-encode "f(string,string,uint256)" "$name" "$symbol" 1000000000000000000000000000)
args=${args#0x}

case "$creation" in
  *"$args") code=${creation%"$args"} ;;
  *) echo "constructor arguments not found at the end of the creation code" >&2; exit 1 ;;
esac

cat > "$OUT" <<SOL
// SPDX-License-Identifier: MIT
pragma solidity 0.8.30;

// Creation code of Ascend's launch token (constructor: name, symbol, totalSupply).
// Generated by script/fetch-token-code.sh from $TOKEN on Elysium testnet.
bytes constant ASCEND_TOKEN_CREATION_CODE = hex"${code#0x}";
SOL
echo "wrote $OUT ($(( (${#code} - 2) / 2 )) bytes)"
